#!/usr/bin/env python3
"""Generate flutter_app/lib/utils/web_labels.dart: field names and categorical values (habitat, diet, migration...) in all
13 languages, taken from the website's translations so the app and the site say the same thing.

    python _scripts/gen_flutter_labels.py        (re-run after changing frontend/src/lib/i18n/{messages,values}.json or translate.ts)
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
I18N = ROOT / "frontend" / "src" / "lib" / "i18n"
OUT = ROOT / "flutter_app" / "lib" / "utils" / "web_labels.dart"


def dart(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace("$", "\\$").replace('"', '\\"').replace("\n", " ") + '"'


def field_keys() -> dict:
    """snake_case field name -> message key, parsed from FIELD_BY_NAME in translate.ts."""
    ts = (I18N / "translate.ts").read_text(encoding="utf-8")
    block = ts[ts.index("const FIELD_BY_NAME"):ts.index("const humanize")]
    return dict(re.findall(r"(\w+): '(\w+)'", block))


def table(rows: dict, langs: list) -> str:
    lines = []
    for key in sorted(rows):
        texts = rows[key]
        en = texts.get("en", "")
        parts = [f"'en': {dart(en)}"] if en else []
        parts += [f"'{l}': {dart(texts[l])}" for l in langs if l != "en" and texts.get(l) and texts[l] != en]
        lines.append(f"  {dart(key)}: {{{', '.join(parts)}}},")
    return "\n".join(lines)


def main() -> None:
    messages = json.loads((I18N / "messages.json").read_text(encoding="utf-8"))
    values = json.loads((I18N / "values.json").read_text(encoding="utf-8"))
    langs = sorted(messages)
    fields = {}
    for name, key in field_keys().items():
        texts = {l: messages[l][key] for l in langs if messages[l].get(key)}
        if texts:
            fields[name] = texts
    OUT.write_text(
        "// GENERATED by _scripts/gen_flutter_labels.py from the website translations - do not edit by hand.\n"
        "// Field names and categorical values (habitat, diet, migration...) in 13 languages; missing languages fall back to English.\n\n"
        "const Map<String, Map<String, String>> kFieldLabels = {\n" + table(fields, langs) + "\n};\n\n"
        "const Map<String, Map<String, String>> kValueLabels = {\n" + table(values, langs) + "\n};\n\n"
        "String _humanize(String s) {\n"
        "  final spaced = s.replaceAll('_', ' ');\n"
        "  return spaced.isEmpty ? spaced : spaced[0].toUpperCase() + spaced.substring(1);\n"
        "}\n\n"
        "/// Label of a species-file field such as `body_mass_g` in [lang].\n"
        "String fieldLabelFor(String lang, String field) {\n"
        "  final texts = kFieldLabels[field];\n"
        "  return texts?[lang] ?? texts?['en'] ?? _humanize(field);\n"
        "}\n\n"
        "/// A categorical value such as `Forest` or `Full migrant` in [lang]; other values are returned unchanged.\n"
        "String valueLabelFor(String lang, String value) {\n"
        "  final texts = kValueLabels[value];\n"
        "  return texts?[lang] ?? texts?['en'] ?? value;\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"{len(fields)} field labels, {len(values)} values -> {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
